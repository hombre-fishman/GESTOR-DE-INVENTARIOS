-- ============================================
-- TABLA CLIENTES
-- ============================================

CREATE TABLE IF NOT EXISTS public.clientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    nombre VARCHAR(150) NOT NULL,

    telefono VARCHAR(20),

    correo VARCHAR(150),

    direccion TEXT,

    activo BOOLEAN NOT NULL DEFAULT TRUE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);


-- Evitar correos repetidos cuando sí exista correo
CREATE UNIQUE INDEX IF NOT EXISTS clientes_correo_unique
ON public.clientes(correo)
WHERE correo IS NOT NULL;



-- ============================================
-- TABLA VENTAS
-- ============================================

CREATE TABLE IF NOT EXISTS public.ventas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    cliente_id BIGINT
        REFERENCES public.clientes(id)
        ON DELETE SET NULL,

    usuario_id UUID
        REFERENCES auth.users(id)
        ON DELETE SET NULL,

    total NUMERIC(12,2)
        NOT NULL
        DEFAULT 0
        CHECK (total >= 0),

    metodo_pago VARCHAR(30)
        CHECK (
            metodo_pago IN (
                'EFECTIVO',
                'TARJETA',
                'TRANSFERENCIA',
                'OTRO'
            )
        ),

    estado VARCHAR(20)
        NOT NULL
        DEFAULT 'COMPLETADA'
        CHECK (
            estado IN (
                'PENDIENTE',
                'COMPLETADA',
                'CANCELADA'
            )
        ),

    created_at TIMESTAMPTZ
        NOT NULL
        DEFAULT NOW()
);



-- ============================================
-- DETALLE DE CADA VENTA
-- ============================================

CREATE TABLE IF NOT EXISTS public.detalle_ventas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    venta_id BIGINT NOT NULL
        REFERENCES public.ventas(id)
        ON DELETE CASCADE,

    producto_id BIGINT NOT NULL
        REFERENCES public.productos(id)
        ON DELETE RESTRICT,

    cantidad INTEGER
        NOT NULL
        CHECK (cantidad > 0),

    precio_unitario NUMERIC(12,2)
        NOT NULL
        CHECK (precio_unitario >= 0),

    subtotal NUMERIC(12,2)
        NOT NULL
        CHECK (subtotal >= 0),

    created_at TIMESTAMPTZ
        NOT NULL
        DEFAULT NOW()
);



-- ============================================
-- ÍNDICES
-- ============================================

CREATE INDEX IF NOT EXISTS idx_ventas_cliente
ON public.ventas(cliente_id);

CREATE INDEX IF NOT EXISTS idx_ventas_usuario
ON public.ventas(usuario_id);

CREATE INDEX IF NOT EXISTS idx_ventas_fecha
ON public.ventas(created_at);

CREATE INDEX IF NOT EXISTS idx_detalle_venta
ON public.detalle_ventas(venta_id);

CREATE INDEX IF NOT EXISTS idx_detalle_producto
ON public.detalle_ventas(producto_id);



