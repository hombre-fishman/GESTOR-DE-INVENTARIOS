ALTER TABLE public.clientes
ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Usuarios autenticados pueden ver clientes"
ON public.clientes
FOR SELECT
TO authenticated
USING (true);

CREATE POLICY "Usuarios autenticados pueden registrar clientes"
ON public.clientes
FOR INSERT
TO authenticated
WITH CHECK (true);

CREATE POLICY "Usuarios autenticados pueden modificar clientes"
ON public.clientes
FOR UPDATE
TO authenticated
USING (true)
WITH CHECK (true);



